#!/usr/bin/env node
/** Generates .env.local with freshly-random local secrets. Never overwrites. */
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';

const file = '.env.local';
if (existsSync(file)) {
  console.log(`${file} already exists — leaving it untouched.`);
  process.exit(0);
}
const body = `# Local secrets for ValueBack. Generated by \`npm run setup\`.
# This file is git-ignored. Do not commit it, do not share it.
# Regenerating APP_ENCRYPTION_KEY makes existing stored redemption codes unreadable.

DATABASE_URL=./data/valueback.db
STORAGE_DIR=./storage
APP_ENCRYPTION_KEY=${randomBytes(32).toString('base64')}
SESSION_TTL_HOURS=720
`;
writeFileSync(file, body, { mode: 0o600 });
console.log(`Wrote ${file} (0600) with a new 32-byte APP_ENCRYPTION_KEY.`);
